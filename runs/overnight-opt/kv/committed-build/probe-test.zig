test "benchmark committed proof refuses an independently expired follower without reading or forgetting" {
    const pr = try Pair.start("pointproof", 0, 89);
    defer pr.deinit();
    const w = &pr.w;
    var fam: Fam0 = .{ .sim = pr.r0.sim };
    defer fam.deinit();
    const ld = try pr.leader(&fam, 5);
    var open = true;
    defer if (open) ld.destroy();
    ld.bench_check = true;
    const t = ld.tier();
    var ids: [4 * bt]u32 = undefined;
    testIds(&ids, 74);
    const sn = try keepBoth(w, t, pr.r0.sim, 1, 0, &ids, &ids);
    defer gpa.destroy(sn);
    try pumpUntil(ld, 1);
    const key = format.pointKey(&ids, bt, &.{});
    try w.waitPresent(key, true);
    try testing.expect(ld.benchPresence(sn.id, ids.len) == .present);
    try testing.expect(ld.benchPresence(sn.id, ids.len + 1) == .unmapped);
    try testing.expect(ld.benchPresence(sn.id + 10, ids.len) == .unmapped);
    try w.send(T.forget, &.{&key});
    try w.waitPresent(key, false);
    try testing.expect(ld.benchPresence(sn.id, ids.len) == .peer_missing);
    try testing.expect(ld.benchPresence(sn.id, ids.len) == .peer_missing);
    try testing.expect(ld.side.store.presence(key));
    try testing.expectEqual(@as(u64, 0), ld.side.store.counts().loaded);
    try testing.expectEqual(@as(usize, 0), fam.reserved);
    const follower = try w.query(key);
    try testing.expectEqual(@as(u8, 0), follower[1]);
    const repaired = try keepBoth(w, t, pr.r0.sim, 2, 0, &ids, &ids);
    defer gpa.destroy(repaired);
    try w.waitPresent(key, true);
    try testing.expect(ld.benchPresence(repaired.id, ids.len) == .present);
    const point = t.vtable.lookup(t.ptr, &want(&ids)) orelse return error.NotFound;
    const done = pollUntilDone(t, try t.vtable.begin(t.ptr, &point));
    try testing.expect(done == .ready);
    const got: *Snap = @ptrCast(@alignCast(done.ready.saved));
    defer pr.r0.sim.freeSnap(got.buf);
    try testing.expect(ld.benchPresence(got.id,ids.len) == .present);
    ld.destroy();
    open = false;
    try pr.finish();
}
