#!/usr/bin/env python3
"""The series the engine's /metrics can emit, built from the source (not from a scrape).

    python3 -I scripts/source_metrics.py [ENGINE_ROOT=~/Workspace/tfref-kstack4] > data/source-metrics.json

Most families are generated by reflection over engine_api structs, so the list is assembled from those structs'
fields, `gauges` lists and `help` tuples, plus the families written out by hand in server/metrics.zig `render`.
"""
import json
import os
import re
import subprocess
import sys

ROOT = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Workspace/tfref-kstack4")


def src(rel):
    return open(os.path.join(ROOT, rel)).read()


def struct_body(text, decl):
    i = text.index(decl)
    j = text.index("{", i)
    depth, k = 0, j
    while True:
        c = text[k]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return text[j + 1:k]
        k += 1


def fields(body, want=("u64",)):
    """Top-level `name: type = default,` fields of a struct body, in order."""
    out, depth = [], 0
    for line in body.split("\n"):
        s = line.strip()
        if depth == 0:
            m = re.match(r"([a-z_0-9]+):\s*([A-Za-z0-9_.\[\]?]+)\s*=", s)
            if m and not s.startswith("//") and not s.startswith("pub "):
                if m.group(2) in want:
                    out.append((m.group(1), m.group(2)))
        depth += s.count("{") - s.count("}")
    return out


def helps(body):
    i = body.find("pub const help = .{")
    if i < 0:
        return {}
    blk = struct_body(body[i:], "pub const help = .")
    return dict(re.findall(r"\.([a-z_0-9]+)\s*=\s*\"((?:[^\"\\]|\\.)*)\"", blk))


def gauges(body):
    m = re.search(r"pub const gauges = \[_\]\[\]const u8\{([^}]*)\}", body)
    return set(re.findall(r"\"([a-z_0-9]+)\"", m.group(1))) if m else set()


def main():
    api = src("zig/src/core/engine_api.zig")
    pc = src("zig/src/core/prompt_cache.zig")
    kv = src("zig/src/core/lanes/kv_parts.zig")
    mz = src("zig/src/server/metrics.zig")
    out = []

    def add(name, kind, group, help_="", labels=(), cond=""):
        out.append({"name": "tensorfold:" + name, "type": kind, "group": group, "labels": list(labels),
                    "help": help_, "condition": cond})

    # families written out in render(), with their literal help text
    lit = {m.group(2): (m.group(1), m.group(3), m.group(4)) for m in re.finditer(
        r"try (gauge|gaugeFloat|family)\(w, \"([a-z_0-9]+)\", \"(counter|gauge)\", \"((?:[^\"\\]|\\.)*)\"", mz)}
    hist = {m.group(1): m.group(2) for m in re.finditer(
        r"try histogram\(w, \"([a-z_0-9]+)\", \"((?:[^\"\\]|\\.)*)\"", mz)}
    conds = {"requests_total": "only once an HTTP reply has been counted", "joules_total": "TF_DS_ENERGY",
             "prompt_tokens_cached_total": "engine keeps prompt states", "prefix_cache_queries_total": "engine keeps prompt states",
             "prefix_cache_hits_total": "engine keeps prompt states", "process_footprint_bytes": "macOS only",
             "device_memory_bytes": "CUDA backend", "device_memory_peak_bytes": "CUDA backend",
             "preemptions_total": "engine counts preemptions"}
    labels = {"requests_total": ("key", "status"), "kv_cache_usage_ratio": ("pool",), "kv_cache_usage_perc": ("stream",)}
    for name, (_, kind, h) in lit.items():
        if name in ("chats_continued", "chats_continued_prefill_tokens"):
            continue  # cacheFamilies, below
        if name.startswith("engram_rowcache"):
            add(name, kind, "engram", h, cond="TF_DS_ENGRAM_METRICS")
            continue
        add(name, kind, "server", h, labels.get(name, ()), conds.get(name, ""))
    for name, h in hist.items():
        if name == "prompt_cache_resume_depth_percent":
            continue
        g = "server"
        add(name, "histogram", g, h, ("le",))
    add("engram_lookup_seconds", "histogram", "engram",
        re.search(r'pub const help = "([^"]+)"', struct_body(api, "pub const EngramStats = struct")).group(1), ("le",),
        "TF_DS_ENGRAM_METRICS")

    cs = struct_body(api, "pub const CacheStats = struct")
    h, g = helps(cs), gauges(cs)
    for n in ("chats_continued", "chats_continued_prefill_tokens"):
        add(n, "counter", "prompt_cache", h[n], cond="prompt cache tier/grouping or TF_DS_CACHE_METRICS")
    for n, _ in fields(cs):
        add("prompt_cache_" + n, "gauge" if n in g else "counter", "prompt_cache", h[n],
            cond="prompt cache tier/grouping or TF_DS_CACHE_METRICS")
    cd = struct_body(api, "pub const CacheDetail = struct")
    h = helps(cd)
    for n, _ in fields(cd):
        add("prompt_cache_" + n, "counter", "prompt_cache_detail", h[n], cond="TF_DS_CACHE_METRICS")
    add("prompt_cache_resume_depth_percent", "histogram", "prompt_cache_detail",
        "The resume depth of finished prompt passes (0/25/50/75/90/99/100 percent buckets).", ("le",), "TF_DS_CACHE_METRICS")
    tc = struct_body(pc, "pub const TierCounts = struct")
    h, g = helps(tc), gauges(tc)
    for n, _ in fields(tc):
        add("spill_" + n, "gauge" if n in g else "counter", "spill", h[n], ("rank",), "disk tier on")
    st = struct_body(kv, "pub const Stats = struct")
    h, g = helps(st), gauges(st)
    for n, _ in fields(st):
        add("kv_shard_" + n, "gauge" if n in g else "counter", "kv_shard", h[n], cond="TF_DS_KV_SHARD")
    pt = struct_body(kv, "pub const Part = struct")
    h = helps(pt)
    for n, _ in fields(pt, want=("u64", "u32")):
        add("kv_shard_part_" + n, "gauge", "kv_shard_part", h.get(n, ""), ("part",), "TF_DS_KV_SHARD")
    rk = struct_body(kv, "pub const Rank = struct")
    h = helps(rk)
    for n, _ in fields(rk):
        add("kv_shard_rank_" + n, "counter", "kv_shard_rank", h[n], ("rank",), "TF_DS_KV_SHARD, a rank reported")
    ps = struct_body(api, "pub const PairStatus = struct")
    h, g = helps(ps), gauges(ps)
    for n, _ in fields(ps, want=("u64", "bool")):
        full = ("pair_" + n) if n in g else n
        add(full, "gauge" if n in g else "counter", "pair", h[n], cond="backend with a broken-pair policy or a disk tier")

    rev = subprocess.run(["git", "-C", ROOT, "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    json.dump({"engine_root": ROOT, "commit": rev, "families": out}, sys.stdout, indent=1)


if __name__ == "__main__":
    main()
