#!/usr/bin/env python3
"""Write COVERAGE.md: every series held for the Sparks, the panel it is on, and what is missing (the tables are
generated; the two closing sections are scripts/coverage_tail.md, written by hand). Reads the saved
dashboards (dashboards-after/<id>.json), the stream inventory, the source list and the panel verification.

    python3 -I scripts/coverage.py
"""
import collections
import datetime as dt
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TF_ID, DGX_ID = "7522360476127199234", "7522324382660689920"
L = lambda p: json.load(open(os.path.join(ROOT, p)))
day = lambda us: dt.datetime.fromtimestamp(us / 1e6, dt.timezone.utc).strftime("%Y-%m-%d") if us else "-"


def panels_by_metric(dash, pattern):
    used = collections.defaultdict(list)
    for t in dash["tabs"]:
        for p in t["panels"]:
            for q in p.get("queries", []):
                for m in set(re.findall(pattern, q.get("query") or "")):
                    if (t["name"], p["title"]) not in used[m]:
                        used[m].append((t["name"], p["title"]))
    return used


def where(lst, n=2):
    s = "; ".join(f"{a} → {b}" for a, b in lst[:n])
    return s + (f" (+{len(lst) - n} more)" if len(lst) > n else "")


def main():
    tf = L(f"dashboards-after/{TF_ID}.json")["v8"]
    dgx = L(f"dashboards-after/{DGX_ID}.json")["v8"]
    before = L(f"dashboards-before/{TF_ID}.json")["v8"]
    streams = {s["name"]: s for s in L("data/streams-metrics.json")["list"]}
    inv = {s["name"]: s for s in L("data/inventory-metrics.json")["streams"]}
    src = L("data/source-metrics.json")
    cov = L("data/dgx-coverage.json")
    used = panels_by_metric(tf, r"tensorfold:[a-z0-9_]+")
    used_before = panels_by_metric(before, r"tensorfold:[a-z0-9_]+")
    used_dgx = panels_by_metric(dgx, r"[a-zA-Z_][a-zA-Z0-9_]*(?=\{)")
    ver = {(p["tab"], p["title"]): p["status"] for p in L(f"data/verify/after-{TF_ID}.json")["panels"]}
    o = []
    A = o.append
    A("# Coverage: every Spark series and the panel it is on (2026-11-23)\n")
    A("Generated by `scripts/coverage.py` from the dashboards as saved in OpenObserve (`dashboards-after/`), the stream listing and the engine source "
      f"(`{src['engine_root']}` at `{src['commit']}`). Panel references are *tab → panel title*.\n")
    A("## Scope rule\n")
    A("- **On a named panel:** every `tensorfold:*` series that holds samples, every host series, every DCGM series, the collector's own scrape series and every "
      "device-level ConnectX (DOCA) counter.\n"
      "- **Through a selector only:** the ConnectX counters split by queue or index (`rx0_*` … `rx19_*`, `tx0_*` … `tx19_*`, `ch0_*`, per-priority and per-interface copies): "
      f"{len(cov['doca_indexed']):,} series a host. One panel each would be thousands of panels that repeat the device totals; the *DGX Sparks → Any series* tab shows any of them by name.\n"
      "- **Not on a panel:** names the nodes stopped sending (retired `tensorfold_*`, `tensorfold_health:*`, the October `spark0` / `spark1` collection) and the empty histogram parent "
      "streams. The retired engine names are in the *Tensorfold → Any series* selector; the rest are listed at the end.\n")
    # ---- engine series
    fams = src["families"]
    A("## Engine series (`tensorfold:*`)\n")
    held = [n for n, s in streams.items() if n.startswith("tensorfold:") and s["stats"]["doc_num"] > 0]
    exp = set()
    for f in fams:
        exp |= {f["name"] + x for x in ("_bucket", "_sum", "_count")} if f["type"] == "histogram" else {f["name"]}
    A(f"- The source can emit **{len(fams)} families** ({len(exp)} series once histograms are split into `_bucket`, `_sum`, `_count`).\n"
      f"- OpenObserve holds **{len(held)}** of them with samples. Missing: " + ", ".join(f"`{n}`" for n in sorted(exp - set(streams))) + ".\n"
      f"- The dashboard referenced **{len([n for n in held if n in used_before])}** before this review and references **{len([n for n in held if n in used])}** now "
      f"({len([n for n in held if n not in used])} left out).\n")
    A("| Family | Type | Labels | In OpenObserve (first sample) | Panels | New |\n|---|---|---|---|---|---|")
    for f in fams:
        names = [f["name"] + x for x in ("_bucket", "_sum", "_count")] if f["type"] == "histogram" else [f["name"]]
        have = [n for n in names if n in streams and streams[n]["stats"]["doc_num"] > 0]
        pl, new = [], False
        for n in names:
            for x in used.get(n, []):
                if x not in pl:
                    pl.append(x)
            if n in used and n not in used_before:
                new = True
        if not have:
            state = "**no**"
        else:
            last = max(streams[n]["stats"]["doc_time_max"] for n in have)
            state = day(min(streams[n]["stats"]["doc_time_min"] for n in have))
            if last < L("data/inventory-metrics.json")["generated_us"] - 86400e6:
                state += f", **stopped {day(last)}**"
        parts = "" if f["type"] != "histogram" else " (`_bucket`, `_sum`, `_count`)"
        A(f"| `{f['name'].replace('tensorfold:', '')}`{parts} | {f['type']} | {', '.join(f['labels']) or '-'} | {state} | {where(pl) or '-'} | {'yes' if new else ''} |")
    A("")
    empties = [k for k, v in ver.items() if v == "empty"]
    A("Panels that return no samples over the last 24 h, and why: " + "; ".join(f"*{a} → {b}*" for a, b in empties) + ". "
      "`joules_total` exists only while `TF_DS_ENERGY` is on (last samples 2026-11-17). The three `engram_rowcache_*` counters have read 0 in every sample since 2026-11-17, "
      "so their ratio is undefined; the panel beside it shows the zero rates.\n")
    # ---- other spark series
    A("## Host, GPU and collector series (dashboard *DGX Sparks*)\n")
    A("| Series | Source | Type | Label sets on the head | Panels |\n|---|---|---|---|---|")
    for grp, svc in (("host", "hostmetrics receiver"), ("dcgm", "dcgm-exporter")):
        for n in cov[grp]:
            s = inv[n]
            ser = next((h["series"] for h in s["hosts"] if h["h"] == "gx10-eb0e"), 0)
            A(f"| `{n}` | {svc} | {s['type']} | {ser} | {where(used_dgx.get(n, []))} |")
    for n in ("up", "scrape_samples_scraped", "scrape_samples_post_metric_relabeling", "scrape_duration_seconds", "scrape_series_added"):
        A(f"| `{n}` | collector, one a scrape job | Gauge | 3 jobs | {where(used_dgx.get(n, []))} |")
    A("")
    A("## ConnectX counters (DOCA telemetry, dashboard *DGX Sparks*)\n")
    A(f"{cov['doca_total']:,} series a host, scraped every 30 s on both Sparks. Device-level counters ({len(cov['doca_device_level'])}) by panel group, "
      "all on the tab *ConnectX: every device counter* (the original *Default* tab keeps its five fabric panels):\n")
    for g, names in cov["doca_groups"].items():
        A(f"- **{g}** ({len(names)}): " + ", ".join(f"`{n}`" for n in names))
    pat = collections.Counter(re.sub(r"\d+", "N", n) for n in cov["doca_indexed"])
    A(f"\nIndexed counters ({len(cov['doca_indexed']):,} series, {len(pat)} name patterns with `N` for the index), selector only (*Any series*):\n")
    A(", ".join(f"`{k}` ×{v}" for k, v in sorted(pat.items())))
    A("")
    # ---- retired
    A("## Held in OpenObserve but no longer sent (no panel)\n")
    ret = collections.defaultdict(list)
    for n, s in streams.items():
        st = s["stats"]
        if n.startswith("tensorfold_health:"):
            ret["`tensorfold_health:*` (the first scraper's copy of /health)"].append(st)
        elif n.startswith("tensorfold_"):
            ret["`tensorfold_*` (the engine's names before 2026-11-10)"].append(st)
        elif any(h["h"] in ("spark0", "spark1") for h in inv[n]["hosts"]):
            ret["label `host` = `spark0` / `spark1` (the October telegraf-style collection: `nstat_*`, `ethtool_*`, `nvidia_*`, `mem_*`, …)"].append(st)
    A("| Family | Streams | First sample | Last sample |\n|---|---|---|---|")
    for k, v in ret.items():
        A(f"| {k} | {len(v)} | {day(min(x['doc_time_min'] for x in v if x['doc_time_min']))} | {day(max(x['doc_time_max'] for x in v))} |")
    hp = [n for n, s in streams.items() if n.startswith("tensorfold:") and s["stats"]["doc_num"] == 0]
    A(f"| histogram parent streams with no samples ({', '.join('`' + n.replace('tensorfold:', '') + '`' for n in sorted(hp))}) | {len(hp)} | - | - |")
    A("")
    tail = open(os.path.join(ROOT, "scripts/coverage_tail.md")).read()
    open(os.path.join(ROOT, "COVERAGE.md"), "w").write("\n".join(o) + "\n" + tail)
    print("lines", len(o))


if __name__ == "__main__":
    main()
